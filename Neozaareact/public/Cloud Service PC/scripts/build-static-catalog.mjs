// Generates a static catalog.js for the embedded (no-backend) Cloud Service
// pricing calculator. Mirrors the merge logic in scripts/build.mjs and the
// baseUsd/inr computation in worker/runtime.js mergedCatalog() using the
// default conversion rate (90 INR/USD) and hourly rate (65 USD/hr), so the
// calculator works client-side without the Cloudflare Worker/D1 database.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const outFile = resolve(root, '..', 'cloud-pricing', 'catalog.js');

const CONVERSION_RATE = 90; // INR per USD
const HOURLY_RATE = 65; // USD per hour

const BUILTIN_FAMILY_ORDER = [
  'Office 365',
  'Modern Workplace',
  'Tenant to Tenant',
  'Landing Zone Implementation',
  'Advisory Services',
  'Cloud Implementation Services',
  'Managed IT & Security',
  'Cloud Managed Operations',
  'Cloud Support',
];

function calculatorFamily(row) {
  const id = row.id;
  if (/^NE0-013-(00[1-5]|00[9]|01[0-9]|020)$/.test(id)) return 'Office 365';
  if (id.startsWith('NE0-019-') || id.startsWith('NE0-020-') || id === 'NE0-013-008') return 'Modern Workplace';
  if (id.startsWith('NE0-017-')) return 'Tenant to Tenant';
  if (id.startsWith('NE0-023-') || id === 'NE0-016-027') return 'Landing Zone Implementation';
  if (id.startsWith('NE0-008-')) return 'Advisory Services';
  if (/^NE0-(009|010|011|012|014|015|021)-/.test(id) || /^NE0-013-00[67]$/.test(id)) return 'Cloud Implementation Services';
  if (/^NE0-016-00[1-4]$/.test(id)) return 'Cloud Support';
  if (id.startsWith('NE0-016-')) return 'Managed IT & Security';
  if (/^NE0-(001|002|003|004|005|006|007|018)-/.test(id)) return 'Cloud Managed Operations';
  throw new Error(`Unmapped default catalogue SKU: ${id}`);
}

const [catalogText, presentationText, supportText, landingZoneText, cloudManagedText] = await Promise.all([
  readFile(resolve(root, 'data/catalog-default.json'), 'utf8'),
  readFile(resolve(root, 'data/catalog-presentation.json'), 'utf8'),
  readFile(resolve(root, 'data/managed-support-packages.json'), 'utf8'),
  readFile(resolve(root, 'data/landing-zone-packages.json'), 'utf8'),
  readFile(resolve(root, 'data/cloud-managed-operations.json'), 'utf8'),
]);

const baseCatalog = JSON.parse(catalogText);
const presentation = JSON.parse(presentationText);
const supportPackages = JSON.parse(supportText);
const landingZonePackages = JSON.parse(landingZoneText);
const cloudManagedOperations = JSON.parse(cloudManagedText);

// Same merge as build.mjs
const defaultCatalog = [
  ...baseCatalog.filter((row) => !row.id.startsWith('NE0-016-') && !/^NE0-(001|002|003)-/.test(row.id)),
  ...cloudManagedOperations,
  ...supportPackages,
  ...landingZonePackages,
].map((row) => ({ ...row, family: calculatorFamily(row), ...(presentation[row.id] || {}) }));

if (!Array.isArray(defaultCatalog) || defaultCatalog.length !== 151) {
  throw new Error(`Expected 151 merged catalogue rows, got ${defaultCatalog.length}`);
}

// Same per-row pricing as mergedCatalog() with no DB overrides.
const rows = defaultCatalog.map((row) => {
  const anchorInr = Number(row.inr);
  const usesUniversalHourlyRate = row.timeUnit === 'Hours';
  const hourlyRateFactor = usesUniversalHourlyRate ? Number(row.hourlyRateFactor || 1) : 1;
  const baseUsd = usesUniversalHourlyRate
    ? Math.round(HOURLY_RATE * hourlyRateFactor * 100) / 100
    : Number(row.baseUsd ?? anchorInr / 90);
  const inr = Math.round(baseUsd * CONVERSION_RATE);
  return {
    ...row,
    hourlyRateFactor,
    baseUsd,
    usd: baseUsd,
    inr,
    cost: inr,
    usesUniversalHourlyRate,
    custom: false,
    updatedAt: null,
    updatedBy: null,
  };
});

const families = BUILTIN_FAMILY_ORDER.map((name, position) => ({ name, position, custom: false }));

const banner = '// AUTO-GENERATED by scripts/build-static-catalog.mjs — do not edit by hand.\n';
const body = `window.PRICE_CATALOG=${JSON.stringify(rows)};window.CALCULATOR_FAMILIES=${JSON.stringify(families)};window.INR_PER_USD_RATE=${CONVERSION_RATE};\n`;
await writeFile(outFile, banner + body);
console.log(`Wrote ${rows.length} catalogue rows to ${outFile}`);
