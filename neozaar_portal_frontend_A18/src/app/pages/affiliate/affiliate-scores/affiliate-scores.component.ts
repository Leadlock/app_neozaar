import { Component, OnInit, inject } from '@angular/core';
import { CommonModule } from '@angular/common';
import { FormsModule } from '@angular/forms';
import { AffiliateService } from '../../../core/services/affiliate/affiliate.service';

@Component({
  selector: 'app-affiliate-scores',
  standalone: true,
  imports: [CommonModule, FormsModule],
  template: `
<div class="crm-page">
  <div class="crm-header">
    <div>
      <h1 class="crm-title">Customer Scores</h1>
      <p class="crm-subtitle">Scores generated by the existing NeoZaar CRM scoring engine — showing only your attributed customers</p>
    </div>
  </div>

  @if (loading) {
    <div class="neo-card" style="text-align:center;padding:3rem;color:var(--crm-text-secondary)">Loading…</div>
  } @else if (!scores.length) {
    <div class="neo-card" style="text-align:center;padding:3rem;color:var(--crm-text-secondary)">
      <p style="font-size:0.9rem;font-weight:600">No scored customers yet</p>
      <p style="font-size:0.78rem;margin-top:0.35rem">Scores appear once customers interact with NeoZaar marketplace pages.</p>
    </div>
  } @else {
    <div class="neo-table-wrap">
      <table class="neo-table">
        <thead>
          <tr>
            <th>Customer</th><th>Email</th><th>Company</th>
            <th>Score</th><th>Score Label</th><th>CRM Stage</th><th>Converted?</th><th>Registered</th>
          </tr>
        </thead>
        <tbody>
          @for (c of scores; track c.id) {
            <tr>
              <td style="font-weight:600">{{ c.name }}</td>
              <td style="color:var(--crm-text-secondary);font-size:0.8rem">{{ c.email }}</td>
              <td>{{ c.company || '—' }}</td>
              <td>
                <span class="neo-badge" [class]="scoreBadge(c.score)">
                  <strong>{{ c.score }}</strong>
                </span>
              </td>
              <td><span class="neo-badge">{{ c.score_label || '—' }}</span></td>
              <td>{{ c.lead_stage || '—' }}</td>
              <td>{{ c.converted_to_opportunity_id ? '✓' : '—' }}</td>
              <td style="font-size:0.8rem;color:var(--crm-text-secondary)">{{ c.created_at | date:'mediumDate' }}</td>
            </tr>
          }
        </tbody>
      </table>
    </div>
    <div style="display:flex;align-items:center;gap:0.75rem;margin-top:1.25rem">
      <button class="neo-btn" [disabled]="page===1" (click)="changePage(-1)">← Prev</button>
      <span style="font-size:0.8rem;color:var(--crm-text-secondary)">Page {{ page }}</span>
      <button class="neo-btn" (click)="changePage(1)">Next →</button>
    </div>
  }
</div>`,
})
export class AffiliateScoresComponent implements OnInit {
  private svc = inject(AffiliateService);
  scores: any[] = [];
  loading = true;
  page    = 1;
  limit   = 20;

  ngOnInit() { this.load(); }

  load() {
    this.loading = true;
    this.svc.getCustomerScores({ page: this.page, limit: this.limit }).subscribe({
      next: (r: any) => { this.scores = r.data || []; this.loading = false; },
      error: () => { this.loading = false; },
    });
  }

  changePage(d: number) { this.page = Math.max(1, this.page + d); this.load(); }

  scoreBadge(score: number): string {
    if (score >= 20) return 'neo-badge-active';
    if (score >= 10) return 'neo-badge-warning';
    return 'neo-badge-gray';
  }
}
